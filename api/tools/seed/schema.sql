-- Tables the seed writes into. Applied before every run, so a fresh database
-- and an existing one end up the same. Column comments record what the source
-- data can and cannot support; read docs/data.md before
-- changing anything here.

CREATE TABLE IF NOT EXISTS properties (
  id INT UNSIGNED NOT NULL COMMENT 'Listing id, kept so citations stay stable',
  full_address VARCHAR(255) NOT NULL,
  post_code VARCHAR(10) NULL,
  postcode_district VARCHAR(5) NULL,
  town VARCHAR(60) NULL COMMENT 'Matched against known towns; null when unrecognised',
  price INT UNSIGNED NOT NULL COMMENT 'Asking price in pounds',
  area_m2 SMALLINT UNSIGNED NULL COMMENT 'Null when the listing gave no floor area; never estimated',
  council_tax_band CHAR(1) NULL COMMENT 'A to H, null for NA, none and TBC',
  bedrooms TINYINT UNSIGNED NULL,
  bathrooms TINYINT UNSIGNED NULL,
  public_rooms TINYINT UNSIGNED NULL,
  property_kind ENUM('residential','plot','commercial','other') NOT NULL,
  house_floor TINYINT UNSIGNED NULL COMMENT 'Storeys as listed; meaning not confirmed',
  has_garage BOOLEAN NOT NULL DEFAULT FALSE,
  has_double_garage BOOLEAN NOT NULL DEFAULT FALSE,
  has_garden BOOLEAN NOT NULL DEFAULT FALSE,
  has_land BOOLEAN NOT NULL DEFAULT FALSE,
  has_central_heating BOOLEAN NOT NULL DEFAULT FALSE,
  is_parking_available BOOLEAN NOT NULL DEFAULT FALSE,
  has_on_street_parking BOOLEAN NOT NULL DEFAULT FALSE,
  has_off_street_parking BOOLEAN NOT NULL DEFAULT FALSE,
  has_ground_floor_bedroom_bathroom BOOLEAN NOT NULL DEFAULT FALSE,
  has_granny_flat BOOLEAN NOT NULL DEFAULT FALSE,
  has_green_energy BOOLEAN NOT NULL DEFAULT FALSE,
  has_electric_vehicle_charge_point BOOLEAN NOT NULL DEFAULT FALSE,
  is_self_contained BOOLEAN NOT NULL DEFAULT FALSE,
  is_new_build BOOLEAN NOT NULL DEFAULT FALSE,
  is_development BOOLEAN NOT NULL DEFAULT FALSE,
  is_development_opportunity BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_properties_price (price),
  KEY idx_properties_bedrooms (bedrooms),
  KEY idx_properties_district (postcode_district),
  KEY idx_properties_town (town),
  KEY idx_properties_kind (property_kind),
  KEY idx_properties_updated_at (updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
  COMMENT='Listing facts. A false flag means the listing did not say so, not that the property lacks it.';

