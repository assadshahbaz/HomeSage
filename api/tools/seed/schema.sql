  ownership_months SMALLINT UNSIGNED NULL COMMENT 'Null when the answer was a start date rather than a duration',
  conservation_area ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  conservation_area_detail TEXT NULL,
  listed_building ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  listed_building_detail TEXT NULL,
  windows_replaced ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  windows_replaced_detail TEXT NULL,
  central_heating ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  central_heating_detail TEXT NULL,
  maintenance_contract ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  maintenance_contract_detail TEXT NULL,
  epc_available ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown'
