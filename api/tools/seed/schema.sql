  epc_available_detail TEXT NULL,
  structural_damage ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  structural_damage_detail TEXT NULL,
  asbestos ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  asbestos_detail TEXT NULL,
  gas_supply ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  gas_supply_detail TEXT NULL,
  water_supply ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  water_supply_detail TEXT NULL,
  electricity_supply ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  electricity_supply_detail TEXT NULL,
  mains_drainage ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  mains_drainage_detail TEXT NULL,
  telephone_line ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown'
    COMMENT 'Whether a line exists. Phone numbers are never stored.',
  telephone_line_detail TEXT NULL,
  broadband ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  broadband_detail TEXT NULL,
  cable_tv ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  cable_tv_detail TEXT NULL,
  shared_cost_responsibility ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  shared_cost_responsibility_detail TEXT NULL,
  major_roof_repairs ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  major_roof_repairs_detail TEXT NULL,
  common_building_insurance ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  common_building_insurance_detail TEXT NULL,
  other_regular_charges ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  other_regular_charges_detail TEXT NULL,
  specialist_work ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  specialist_work_detail TEXT NULL,
  guarantee_available ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  guarantee_available_detail TEXT NULL,
  boundaries_moved ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  boundaries_moved_detail TEXT NULL,
  received_notices ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  received_notices_detail TEXT NULL,
  public_right_of_way ENUM('yes','no','unknown','not_applicable') NOT NULL DEFAULT 'unknown',
  public_right_of_way_detail TEXT NULL,
  gas_supplier VARCHAR(100) NULL,
  electricity_supplier VARCHAR(100) NULL,
  water_supplier VARCHAR(100) NULL,
  broadband_supplier VARCHAR(100) NULL,
  heating_supplier VARCHAR(100) NULL,
  cable_tv_supplier VARCHAR(100) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (property_id),
  CONSTRAINT fk_disclosures_property FOREIGN KEY (property_id) REFERENCES properties (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
  COMMENT='Seller questionnaire answers. Unknown means the seller did not answer, not no.';
